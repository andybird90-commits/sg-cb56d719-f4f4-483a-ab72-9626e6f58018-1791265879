import { RequireAuth } from "@/components/RequireAuth";
import { Layout } from "@/components/Layout";
import { useAuth } from "@/contexts/AuthContext";
import { useRouter } from "next/router";
import { useEffect, useState } from "react";
import { supabase } from "@/lib/supabase";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Alert, AlertDescription } from "@/components/ui/alert";
import { ArrowLeft } from "lucide-react";
import Link from "next/link";

interface Company {
  id: string;
  name: string;
}

interface Opportunity {
  id: string;
  name: string;
  company_id: string | null;
  project_reference: string | null;
}

function NewProjectContent() {
  const { profile } = useAuth();
  const router = useRouter();
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [companies, setCompanies] = useState<Company[]>([]);
  const [opportunities, setOpportunities] = useState<Opportunity[]>([]);
  const [formData, setFormData] = useState({
    name: "",
    opportunity_id: "",
    client_company_id: "",
    start_date: "",
    end_date: "",
    status: "live",
    agreed_fee_value: "",
    notes: "",
    opportunity_reference: "", // Track where this came from
  });

  // Check if we're coming from an opportunity
  const fromOpportunityId = router.query.opportunity_id as string;

  useEffect(() => {
    if (profile && profile.role !== "admin" && profile.role !== "director") {
      router.push("/projects");
    }
    fetchData();
    
    // If coming from an opportunity, pre-populate the opportunity reference
    const opportunityId = router.query.opportunity_id as string;
    if (opportunityId) {
      fetchOpportunityData(opportunityId);
    }
  }, [profile, router]);

  const fetchData = async () => {
    const { data: companiesData } = await supabase
      .from("companies")
      .select("id, name")
      .order("name");

    setCompanies(companiesData || []);

    // Fetch all non-archived opportunities that haven't been converted to projects yet
    // Cast supabase to any to prevent "Type instantiation is excessively deep" error
    const { data: opportunitiesData } = await (supabase as any)
      .from("opportunities")
      .select("id, name, company_id, project_reference")
      .is("linked_project_id", null)
      .eq("archived", false)
      .order("name");

    if (opportunitiesData) {
      setOpportunities(opportunitiesData);
    }
  };

  const fetchOpportunityData = async (opportunityId: string) => {
    // Cast supabase to any to prevent type errors claiming columns don't exist
    const { data } = await (supabase as any)
      .from("opportunities")
      .select("name, company_id, project_reference")
      .eq("id", opportunityId)
      .single();
    
    const opp = data;

    if (opp) {
      setFormData(prev => ({
        ...prev,
        name: opp.name || "",
        opportunity_id: opportunityId, // Auto-set the opportunity_id
        client_company_id: opp.company_id || "",
        opportunity_reference: opp.project_reference || "", // The Opp ref is stored in project_reference on the opp table
      }));
    }
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setLoading(true);
    setError("");

    try {
      const payload = {
        name: formData.name,
        client_company_id: formData.client_company_id,
        status: "live" as "pipeline" | "live" | "on_hold" | "completed" | "cancelled",
        opportunity_id: formData.opportunity_id || null,
        start_date: formData.start_date || null,
        end_date: formData.end_date || null,
        agreed_fee_value: formData.agreed_fee_value ? parseFloat(formData.agreed_fee_value) : null,
        notes: formData.notes || null,
        opportunity_reference: formData.opportunity_reference || null, // Store opp reference
        // project_reference will be auto-generated by the database trigger
      };

      const { data, error: insertError } = await supabase
        .from("projects")
        .insert([payload])
        .select()
        .single();

      if (insertError) {
        console.error("Failed to create project:", insertError);
        setError("Failed to create project: " + insertError.message);
        setLoading(false);
        return;
      }

      if (!data?.id) {
        console.error("No project id returned after insert");
        setError("Project created but id is missing.");
        setLoading(false);
        return;
      }

      // If project is linked to an opportunity, update the opportunity
      // CRITICAL FIX: Archive the opportunity AND set status to closed_won
      if (formData.opportunity_id) {
        const { error: oppUpdateError } = await supabase
          .from("opportunities")
          .update({
            linked_project_id: data.id,
            status: "closed_won",
            archived: true
            // DON'T update stage - keep it at whatever stage it was (bid/high_potential/secured)
          })
          .eq("id", formData.opportunity_id);

        if (oppUpdateError) {
          console.error("Failed to link opportunity:", oppUpdateError);
          // Don't fail the whole operation, just log the error
        }
      }

      // Success - redirect to the new project detail page
      setLoading(false);
      router.push(`/projects/${data.id}`);
      
    } catch (err) {
      console.error("Unexpected error creating project:", err);
      setError("Unexpected error creating project.");
      setLoading(false);
    }
  };

  return (
    <Layout>
      <div className="max-w-3xl mx-auto space-y-4 sm:space-y-6">
        <div className="flex flex-col sm:flex-row sm:items-center gap-3 sm:gap-4">
          <Link href="/projects">
            <Button variant="ghost" size="sm" className="gap-2 self-start">
              <ArrowLeft className="w-4 h-4" />
              Back
            </Button>
          </Link>
          <div>
            <h1 className="text-2xl sm:text-3xl font-bold text-slate-900">Add New Project</h1>
            <p className="text-sm sm:text-base text-slate-600 mt-1">Create a new project</p>
          </div>
        </div>

        <Card>
          <CardHeader>
            <CardTitle className="text-lg sm:text-xl">Project Information</CardTitle>
          </CardHeader>
          <CardContent>
            <form onSubmit={handleSubmit} className="space-y-4">
              {error && (
                <Alert variant="destructive">
                  <AlertDescription className="text-sm">{error}</AlertDescription>
                </Alert>
              )}

              <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                <div className="space-y-2">
                  <Label htmlFor="status" className="text-sm sm:text-base">Status</Label>
                  <Select
                    value={formData.status}
                    onValueChange={(value) => setFormData({ ...formData, status: value })}
                  >
                    <SelectTrigger className="h-10 sm:h-11">
                      <SelectValue />
                    </SelectTrigger>
                    <SelectContent>
                      <SelectItem value="pipeline">Pipeline</SelectItem>
                      <SelectItem value="live">Live</SelectItem>
                      <SelectItem value="on_hold">On Hold</SelectItem>
                      <SelectItem value="completed">Completed</SelectItem>
                      <SelectItem value="cancelled">Cancelled</SelectItem>
                    </SelectContent>
                  </Select>
                </div>
              </div>

              <div className="bg-blue-50 border border-blue-200 rounded-lg p-4 mb-6">
                <p className="text-sm text-blue-800">
                  <strong>Note:</strong> A P-prefixed reference (e.g., P26001) will be automatically generated for this project.
                </p>
              </div>

              {/* Project Name */}
              <div>
                <label className="block text-sm font-medium text-gray-700 mb-2">
                  Project Name *
                </label>
                <input
                  type="text"
                  required
                  value={formData.name}
                  onChange={(e) => setFormData({ ...formData, name: e.target.value })}
                  className="w-full px-4 py-2 border border-gray-300 rounded-lg focus:ring-2 focus:ring-blue-500 focus:border-transparent"
                  placeholder="Enter project name"
                />
              </div>

              {formData.opportunity_reference && (
                <div className="space-y-2">
                  <Label htmlFor="opportunity_reference" className="text-sm sm:text-base">Opportunity Reference</Label>
                  <Input
                    id="opportunity_reference"
                    value={formData.opportunity_reference}
                    className="h-10 sm:h-11 bg-slate-50"
                    readOnly
                    disabled
                  />
                  <p className="text-xs text-slate-500">
                    This project originated from opportunity {formData.opportunity_reference}
                  </p>
                </div>
              )}

              <div className="space-y-2">
                <Label htmlFor="client_company_id" className="text-sm sm:text-base">Client Company *</Label>
                <Select
                  value={formData.client_company_id}
                  onValueChange={(value) => setFormData({ ...formData, client_company_id: value })}
                >
                  <SelectTrigger className="h-10 sm:h-11">
                    <SelectValue placeholder="Select a company" />
                  </SelectTrigger>
                  <SelectContent>
                    {companies.map((company) => (
                      <SelectItem key={company.id} value={company.id}>
                        {company.name}
                      </SelectItem>
                    ))}
                  </SelectContent>
                </Select>
              </div>

              {/* CRITICAL FIX: Hide opportunity dropdown when coming from an opportunity */}
              {!fromOpportunityId && (
                <div className="space-y-2">
                  <Label htmlFor="opportunity_id" className="text-sm sm:text-base">Linked Opportunity</Label>
                  <Select
                    value={formData.opportunity_id}
                    onValueChange={(value) => setFormData({ ...formData, opportunity_id: value })}
                  >
                    <SelectTrigger className="h-10 sm:h-11">
                      <SelectValue placeholder="Select an opportunity (optional)" />
                    </SelectTrigger>
                    <SelectContent>
                      {opportunities.map((opp) => (
                        <SelectItem key={opp.id} value={opp.id}>
                          {opp.name}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>
              )}

              <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
                <div className="space-y-2">
                  <Label htmlFor="start_date" className="text-sm sm:text-base">Start Date</Label>
                  <Input
                    id="start_date"
                    type="date"
                    value={formData.start_date}
                    onChange={(e) => setFormData({ ...formData, start_date: e.target.value })}
                    className="h-10 sm:h-11"
                  />
                </div>

                <div className="space-y-2">
                  <Label htmlFor="end_date" className="text-sm sm:text-base">End Date</Label>
                  <Input
                    id="end_date"
                    type="date"
                    value={formData.end_date}
                    onChange={(e) => setFormData({ ...formData, end_date: e.target.value })}
                    className="h-10 sm:h-11"
                  />
                </div>

                <div className="space-y-2">
                  <Label htmlFor="agreed_fee_value" className="text-sm sm:text-base">Agreed Fee Value (£)</Label>
                  <Input
                    id="agreed_fee_value"
                    type="number"
                    step="0.01"
                    value={formData.agreed_fee_value}
                    onChange={(e) => setFormData({ ...formData, agreed_fee_value: e.target.value })}
                    className="h-10 sm:h-11"
                  />
                </div>
              </div>

              <div className="space-y-2">
                <Label htmlFor="notes" className="text-sm sm:text-base">Notes</Label>
                <Textarea
                  id="notes"
                  value={formData.notes}
                  onChange={(e) => setFormData({ ...formData, notes: e.target.value })}
                  rows={4}
                  className="text-sm sm:text-base"
                />
              </div>

              <div className="flex flex-col sm:flex-row gap-3">
                <Button type="submit" disabled={loading} className="h-10 sm:h-11">
                  {loading ? "Creating..." : "Create Project"}
                </Button>
                <Link href="/projects" className="w-full sm:w-auto">
                  <Button type="button" variant="outline" className="w-full h-10 sm:h-11">
                    Cancel
                  </Button>
                </Link>
              </div>
            </form>
          </CardContent>
        </Card>
      </div>
    </Layout>
  );
}

export default function NewProjectPage() {
  return (
    <RequireAuth>
      <NewProjectContent />
    </RequireAuth>
  );
}